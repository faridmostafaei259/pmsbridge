"""Generate docs/tools.md from the tools registered with the MCP server.

Usage:
    python scripts/gen_tool_docs.py           # write docs/tools.md
    python scripts/gen_tool_docs.py --check   # exit 1 if the file is missing or out of date

Every tool module under `pmsbridge.mcp.tools` that exists is loaded (the same discovery the server
uses), and each tool's name, description, parameters and whether it changes data are read from what
the server publishes, so the page cannot drift from the code.
"""

from __future__ import annotations

import argparse
import asyncio
import sys
from collections.abc import Mapping
from pathlib import Path

from mcp.server.mcpserver import MCPServer

from pmsbridge.mcp.server import load_tool_modules, tool_module_names

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "tools.md"

INTRO = """\
# Tools

These are the tools an AI assistant can use once it is connected to pmsbridge. The same tools work
for every supported property management system. Tools that start with the name of a system (for
example `guesty_`) only work with connections to that system.

- Every tool that works on a connection takes an optional `connection` argument: the name or id of
  the connection, as shown by `list_connections`. It can be left out when the assistant may use only
  one connection.
- An assistant can only use the connections the person chose when they approved it. Asking for any
  other connection gets the same answer as asking for one that does not exist.
- Tools marked "changes data" only work on connections where an administrator has allowed changes
  (see [Allow changes](user-guide.md#allow-changes)). They are never repeated automatically: if one
  times out, the assistant is told the outcome is unknown.
- Lists are limited in size, and every call stops after 25 seconds.
- Tool names, parameters and results are only ever added to in updates, never renamed or removed.
"""


def _kind(schema: Mapping[str, object]) -> str:
    """A short description of a JSON schema type."""
    if "enum" in schema:
        values = schema["enum"]
        if isinstance(values, list):
            return " or ".join(f"`{value}`" for value in values)
    for key in ("anyOf", "oneOf"):
        options = schema.get(key)
        if isinstance(options, list):
            names = [_kind(option) for option in options if option.get("type") != "null"]
            optional = any(option.get("type") == "null" for option in options)
            text = " or ".join(dict.fromkeys(names)) or "value"
            return f"{text} (optional)" if optional else text
    kind = schema.get("type")
    if kind == "array":
        items = schema.get("items")
        inner = _kind(items) if isinstance(items, dict) else "value"
        return f"list of {inner}"
    if isinstance(kind, str):
        return kind
    return "value"


def _paragraphs(text: str) -> str:
    return "\n\n".join(" ".join(block.split()) for block in text.strip().split("\n\n"))


def _cell(text: str) -> str:
    return " ".join(text.replace("|", "/").split())


def _parameters(schema: Mapping[str, object]) -> str:
    properties = schema.get("properties")
    if not isinstance(properties, dict) or not properties:
        return "This tool takes no arguments.\n"
    required = schema.get("required")
    needed = set(required) if isinstance(required, list) else set()
    lines = ["| Argument | Type | Required | Description |", "|---|---|---|---|"]
    for name, spec in properties.items():
        if not isinstance(spec, dict):
            continue
        description = _cell(str(spec.get("description", "")))
        lines.append(
            f"| `{name}` | {_cell(_kind(spec))} | {'yes' if name in needed else 'no'} "
            f"| {description} |"
        )
    return "\n".join(lines) + "\n"


def render() -> str:
    server = MCPServer("pmsbridge")
    load_tool_modules(server, tool_module_names())
    tools = sorted(asyncio.run(server.list_tools()), key=lambda tool: tool.name)
    out = ["<!-- Generated by scripts/gen_tool_docs.py. Do not edit by hand. -->", "", INTRO]
    if not tools:
        out.append("No tools are registered yet.\n")
    for tool in tools:
        changes = bool(tool.annotations and tool.annotations.destructive_hint)
        out.append(f"## `{tool.name}`\n")
        out.append(("**Changes data.**" if changes else "**Read only.**") + "\n")
        out.append(_paragraphs(tool.description) + "\n")
        out.append(_parameters(tool.input_schema))
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate docs/tools.md.")
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is out of date")
    args = parser.parse_args(argv)
    content = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else None
        if current != content:
            sys.stderr.write(
                f"{OUTPUT.relative_to(ROOT)} is out of date. "
                "Run: uv run python scripts/gen_tool_docs.py\n"
            )
            return 1
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    sys.stdout.write(f"Wrote {OUTPUT.relative_to(ROOT)}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
